                    icon = Icons.Default.Bookmark,
                    title = "Watchlist y Modo Offline (Room)",
                    description = "Guarda tus animes favoritos y accede a ellos sin conexión a internet."
                )
                FeatureRow(
                    icon = Icons.Default.Star,
                    title = "Calificaciones con 5 Estrellas",
                    description = "Puntúa tus animes favoritos directamente desde los detalles."
                )
            }

            Button(
                onClick = onFinished,
                modifier = Modifier
                    .fillMaxWidth()
